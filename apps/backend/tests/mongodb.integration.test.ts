import { test } from 'node:test';
import assert from 'node:assert/strict';
import mongoose from 'mongoose';
import { UserModel } from '../src/database/models/User.model.js';
import { WorkspaceModel } from '../src/database/models/Workspace.model.js';
import { WorkspaceMemberModel } from '../src/database/models/WorkspaceMember.model.js';
import { ProjectModel } from '../src/database/models/Project.model.js';
import { ScriptModel } from '../src/database/models/Script.model.js';
import { SceneModel } from '../src/database/models/Scene.model.js';
import { StoryboardModel } from '../src/database/models/Storyboard.model.js';
import { SessionModel } from '../src/database/models/Session.model.js';
import { authService } from '../src/modules/auth/auth.service.js';
import { hashToken } from '../src/modules/auth/session.service.js';
import { projectService } from '../src/modules/projects/project.service.js';
import { scriptService } from '../src/modules/scripts/script.service.js';
import { storyboardService } from '../src/modules/storyboards/storyboard.service.js';
import { sceneService } from '../src/modules/scenes/scene.service.js';
import { providerManager } from '../src/modules/providers/provider.manager.js';
import { MockAIProvider } from '../src/modules/providers/adapters/mock.adapter.js';
import { ProviderRequest } from '@ai-video-studio/shared-types';

// Explicit opt-in; only a dedicated database ending in _test is accepted.
test('MongoDB: registration, content versions, scene timing, isolation, rollback and deletion', { skip: !process.env.MONGODB_TEST_URI }, async t => {
  const uri = process.env.MONGODB_TEST_URI!;
  const parsed = new URL(uri);
  assert(/_test$/.test(parsed.pathname.slice(1)), 'MONGODB_TEST_URI must name a dedicated database ending in _test');
  await mongoose.connect(uri, { serverSelectionTimeoutMS: 5000 });
  const users: string[] = [], workspaces: string[] = [], projects: string[] = [];
  t.after(async () => {
    // Only remove records created by this test, never the whole database.
    await SessionModel.deleteMany({ userId: { $in: users } });
    await SceneModel.deleteMany({ projectId: { $in: projects } });
    await StoryboardModel.deleteMany({ projectId: { $in: projects } });
    await ScriptModel.deleteMany({ projectId: { $in: projects } });
    await ProjectModel.deleteMany({ _id: { $in: projects } });
    await WorkspaceMemberModel.deleteMany({ userId: { $in: users } });
    await WorkspaceModel.deleteMany({ _id: { $in: workspaces } });
    await UserModel.deleteMany({ _id: { $in: users } });
    await mongoose.disconnect();
  });
  const mockProvider = new MockAIProvider();
  t.mock.method(providerManager, 'execute', (request: ProviderRequest) => mockProvider.execute(request));
  const suffix = new mongoose.Types.ObjectId().toString();
  const account = await authService.register('Integration User', suffix + '@example.test', 'test-password-123456');
  users.push(account.user.id); workspaces.push(account.workspace.id);
  const login = await authService.login(suffix + '@example.test', 'test-password-123456');
  assert(await SessionModel.findOne({ tokenHash: hashToken(login.token) }));
  const project = await projectService.createProject(account.workspace.id, account.user.id, { title: 'Integration project', creationType: 'prompt' });
  projects.push(project.id);
  const script = await scriptService.generateScript(project.id, account.user.id, { prompt: 'Explain computers' });
  await assert.rejects(storyboardService.generateStoryboardFromScript(project.id, script.id, account.user.id), /Approve the script/);
  await scriptService.approveScript(script.id, account.user.id);
  const board = await storyboardService.generateStoryboardFromScript(project.id, script.id, account.user.id);
  const scenes = await sceneService.listProjectScenes(project.id, account.user.id);
  assert.equal(board.scenes[0].sceneId, scenes[0].id);
  await storyboardService.approveStoryboard(board.id, account.user.id);
  await sceneService.updateScene(scenes[0].id, account.user.id, { duration: 18, narration: 'Edited narration' });
  const edited = await sceneService.listProjectScenes(project.id, account.user.id);
  assert.equal(edited[1].timeline.startTime, 18);
  assert.equal((await StoryboardModel.findById(board.id))!.status, 'draft');
  assert.equal((await ProjectModel.findById(project.id))!.settings.duration, 73);
  await assert.rejects(sceneService.getSceneById(scenes[0].id, new mongoose.Types.ObjectId().toString()));
  // Inject a failure after the new board has been written; the real transaction must roll back.
  const boardCount = await StoryboardModel.countDocuments({ projectId: project.id });
  const sceneCount = await SceneModel.countDocuments({ projectId: project.id });
  const failure = t.mock.method(SceneModel, 'insertMany', async () => { throw new Error('Injected insert failure'); });
  await assert.rejects(storyboardService.generateStoryboardFromScript(project.id, script.id, account.user.id), /Injected insert failure/);
  failure.mock.restore();
  assert.equal(await StoryboardModel.countDocuments({ projectId: project.id }), boardCount);
  assert.equal(await SceneModel.countDocuments({ projectId: project.id }), sceneCount);
  assert.equal((await ProjectModel.findById(project.id))!.storyboardId!.toString(), board.id);
  const nextBoard = await storyboardService.generateStoryboardFromScript(project.id, script.id, account.user.id);
  assert.equal(nextBoard.version, 2);
  assert.equal(await SceneModel.countDocuments({ storyboardId: board.id }), scenes.length);
  assert.equal((await sceneService.listProjectScenes(project.id, account.user.id)).length, scenes.length);
  const nextScript = await scriptService.generateScript(project.id, account.user.id, { prompt: 'Explain networks' });
  assert.equal(nextScript.version, 2);
  assert.equal((await ScriptModel.findById(script.id))!.status, 'superseded');
  assert.equal((await ProjectModel.findById(project.id))!.storyboardId, null);
  const revision = nextScript.get('__v') || 0;
  const edits = { title: 'Edited script title', sections: nextScript.toObject().sections.map(section => ({ ...section, narration: section.narration + ' Edited.' })), expectedRevision: revision };
  const draft = await scriptService.updateScript(nextScript.id, account.user.id, edits);
  assert.equal(draft.title, 'Edited script title');
  assert.equal(draft.id, nextScript.id);
  assert.equal(draft.status, 'draft');
  assert(draft.totalWordCount > nextScript.totalWordCount);
  await assert.rejects(scriptService.updateScript(nextScript.id, account.user.id, edits), /changed in another session/);
  await assert.rejects(scriptService.approveScript(draft.id, account.user.id, revision), /changed in another session/);
  await assert.rejects(scriptService.updateScript(draft.id, new mongoose.Types.ObjectId().toString(), { ...edits, expectedRevision: draft.get('__v') || 0 }));
  await WorkspaceMemberModel.updateOne({ workspaceId: account.workspace.id, userId: account.user.id }, { role: 'viewer' });
  await assert.rejects(scriptService.updateScript(draft.id, account.user.id, { ...edits, expectedRevision: draft.get('__v') || 0 }));
  await WorkspaceMemberModel.updateOne({ workspaceId: account.workspace.id, userId: account.user.id }, { role: 'owner' });
  const approved = await scriptService.approveScript(draft.id, account.user.id, draft.get('__v') || 0);
  const approvedBoard = await storyboardService.generateStoryboardFromScript(project.id, approved.id, account.user.id);
  const revised = await scriptService.updateScript(approved.id, account.user.id, { ...edits, title: 'New draft from approved script', expectedRevision: approved.get('__v') || 0 });
  assert.notEqual(revised.id, approved.id);
  assert.equal(revised.version, 3);
  assert.equal(revised.status, 'draft');
  assert.equal((await ScriptModel.findById(approved.id))!.title, 'Edited script title');
  assert.equal((await ProjectModel.findById(project.id))!.scriptId!.toString(), revised.id);
  assert.equal((await ProjectModel.findById(project.id))!.storyboardId, null);
  assert.equal((await StoryboardModel.findById(approvedBoard.id))!.status, 'superseded');
  await projectService.deleteProject(project.id, account.user.id);
  await assert.rejects(projectService.getProjectById(project.id, account.user.id), /Project not found/);
  await assert.rejects(sceneService.getSceneById(scenes[0].id, account.user.id), /Project not found/);
});
